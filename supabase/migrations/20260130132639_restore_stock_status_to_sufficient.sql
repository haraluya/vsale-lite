-- ============================================================
-- Restore Stock Status to Sufficient
-- Created: 2026-01-30
-- ============================================================

-- 說明：
-- 修復問題：之前的 Migration 錯誤地將所有 stock = 0 的商品設為 'out_of_stock'
-- 本系統支援負庫存銷售，stock_status 應該由管理員手動控制
-- 恢復所有商品的 stock_status 為預設值 'sufficient'

-- ============================================================
-- 恢復所有商品的庫存狀態為「充足」
-- ============================================================

UPDATE products
SET stock_status = 'sufficient'
WHERE stock_status != 'sufficient';

-- ============================================================
-- 說明
-- ============================================================

-- 此 Migration 將所有非 'sufficient' 的商品恢復為 'sufficient'
-- 管理員可以在後台手動調整個別商品的庫存狀態
