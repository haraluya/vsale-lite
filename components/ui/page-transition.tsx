'use client'

import { useEffect, useState } from 'react'

/**
 * MONSKR Logo 頁面過渡動畫
 * 初次載入時顯示，字母逐一描繪後淡出
 */
export function PageTransition() {
  const [phase, setPhase] = useState<'drawing' | 'filled' | 'exit' | 'done'>('drawing')

  useEffect(() => {
    // 檢查是否已經播放過（同一 session 內只播放一次）
    if (sessionStorage.getItem('transition-played')) {
      setPhase('done')
      return
    }

    // 描繪完成 → 填色
    const fillTimer = setTimeout(() => setPhase('filled'), 1800)
    // 填色完成 → 退場
    const exitTimer = setTimeout(() => setPhase('exit'), 2400)
    // 退場完成 → 移除
    const doneTimer = setTimeout(() => {
      setPhase('done')
      sessionStorage.setItem('transition-played', '1')
    }, 3000)

    return () => {
      clearTimeout(fillTimer)
      clearTimeout(exitTimer)
      clearTimeout(doneTimer)
    }
  }, [])

  if (phase === 'done') return null

  return (
    <div
      className={`page-transition-overlay ${phase === 'exit' ? 'page-transition-exit' : ''}`}
      aria-hidden="true"
    >
      <svg
        viewBox="0 0 599.33 101.53"
        className="page-transition-logo"
        xmlns="http://www.w3.org/2000/svg"
      >
        {/* M */}
        <path
          className={`page-transition-letter letter-1 ${phase === 'filled' || phase === 'exit' ? 'letter-filled' : ''}`}
          d="M25.67,97.31l2.04-37.2,22.69,25.37c.32.23,1.8,1.59,3,1.6h.1s.1,0,.1,0c1.2-.02,2.68-1.38,3-1.6l22.68-25.37,2.05,37.2c.3,5.52.87,4.4,5.6,3.22,2.68-.67,4.06-1.36,7.47-1.36,3.07,0,3.19.45,5.66,1.02,5.43,1.25,7.2,3.14,6.91-2.72-1.01-20.21-4.3-91.61-6.11-93.24-.58-.52-1.42-.57-2.65.14-15.4,17.3-27.87,32.07-43.22,49.3-.35.4-.87.66-1.4.76l-.1-.02-.1.02c-.53-.1-1.04-.37-1.4-.76C36.66,36.44,24.19,21.67,8.78,4.37c-1.22-.71-2.07-.66-2.64-.14C4.33,5.86,1.04,77.26.03,97.47c-.29,5.86,1.48,3.97,6.91,2.72,2.47-.57,2.59-1.02,5.66-1.02,3.4,0,4.79.69,7.46,1.36,4.73,1.18,5.3,2.3,5.6-3.22Z"
        />
        {/* O */}
        <path
          className={`page-transition-letter letter-2 ${phase === 'filled' || phase === 'exit' ? 'letter-filled' : ''}`}
          d="M171.58,96.39c-17.71,0-23.54,13.12-39.16-2.68-4.7-4.76-8.54-10.36-11.26-16.57-2.97-6.76-4.62-14.24-4.62-22.11,0-30.4,24.64-55.04,55.04-55.04,30.4,0,55.04,24.64,55.04,55.04,0,7.86-1.65,15.34-4.62,22.11-2.73,6.21-6.56,11.81-11.26,16.57-15.61,15.81-21.45,2.68-39.16,2.68h0ZM171.58,29.1c-14.33,0-25.94,11.61-25.94,25.94s11.61,25.94,25.94,25.94c14.32,0,25.94-11.61,25.94-25.94,0-14.33-11.61-25.94-25.94-25.94Z"
        />
        {/* N */}
        <path
          className={`page-transition-letter letter-3 ${phase === 'filled' || phase === 'exit' ? 'letter-filled' : ''}`}
          d="M318.74,100.19c2.25,1.84,5.48,2.16,5.48-1.76l.64-89c0-5.21-3.54-5.24-8.25-5.24h-5.48c-6.01,0-10.55-1.16-10.55,4.58v44.33S243.49,6.04,243.49,6.04c-4.4-3.52-7.04-2.13-7.04,2.76v86.71c0,7.73.64,5.93,6.62,4.64,2.28-.49,2.73-.89,5.52-.89,2.93,0,3.05.34,5.42.87,5.23,1.17,6.71,3.08,6.71-3.04v-43.98s51.78,41.95,51.78,41.95l6.24,5.13Z"
        />
        {/* S */}
        <path
          className={`page-transition-letter letter-4 ${phase === 'filled' || phase === 'exit' ? 'letter-filled' : ''}`}
          d="M375.55,101.51c27.51,0,39.42-12.56,39.42-30,0-13.4-7.03-22.47-27.81-28.75l-13.75-4.19c-5.04-1.54-7.34-3.35-7.34-6.98,0-3.77,3.36-6.56,10.09-6.56,6.92,0,11.26,1.96,15,4.98,2.37,1.91,3.92.13,6.06-1.92l7.55-7.23c2.34-2.24,4.97-3.8,2.62-5.99-6.24-5.82-16.09-10.78-32.75-10.78-18.49,0-35.45,9.63-35.45,28.33,0,15.63,10.69,24,25.82,28.61l12.22,3.77c6.88,2.09,10.24,4.05,10.24,8.09,0,5.3-4.89,7.54-13.14,7.54-8.93,0-14.81-3.4-19.49-7.99-2.67-2.61-4.17-1-7.39,1.21l-8.37,5.73c-3.18,2.18-7.18,4.15-4.39,7.02,7.06,7.25,19.91,15.09,40.86,15.09Z"
        />
        {/* K */}
        <path
          className={`page-transition-letter letter-5 ${phase === 'filled' || phase === 'exit' ? 'letter-filled' : ''}`}
          d="M511.58,100.14c0-.63-.12-1.35-.21-1.8-.11-.53-1.63-3.04-1.63-3.05-.08-.12-3.97-5.44-7.86-10.76l-24.97-38.13,28.22-36.99c3.81-5,1.95-5.25-4.09-5.25h-11.92c-4.41,0-7.61-.63-10.22,2.89l-27.8,44.71V7.42c0-1.8-1.46-3.25-3.25-3.25h-14.11c-4.2,0-8.59-.79-8.59,3.26v86.27c0,8.13.85,7.8,8.3,7.8h9.36c6.22,0,8.29.62,8.29-5.98v-24.02c15.5-3.99,20.84,14.1,28.96,26.54.85,1.31,3.07,4.2,5.91,3.35,3.23-.96,7.07-2.31,11.42-2.31,4.93-.42,12.62,3.32,13.92,2.09.17-.16.23-.45.25-.78.01-.07.02-.15,0-.24Z"
        />
        {/* R */}
        <path
          className={`page-transition-letter letter-6 ${phase === 'filled' || phase === 'exit' ? 'letter-filled' : ''}`}
          d="M597.47,95.29c-.17-.24-15.51-21.23-15.68-21.47,11.41-6.3,17.54-17.46,17.54-31.49,0-21.61-14.69-38.21-40.78-38.22h-21.43c-2.69,0-5.28-.12-7.55.02-3.95-.07-7.81-.53-7.81,3.27v86.27c0,.64,0,1.21.02,1.75-.08,2,.14,3.34.62,4.25.01.03.03.06.05.09.06.1.11.2.17.28.37.57.89.92,1.62,1.12,1.24.4,2.93.35,5.04.31.26,0,.5,0,.78,0h9.36c1.84,0,3.28.03,4.44-.06,2.7-.13,3.85-.87,3.85-4.84v-25.2c13.93,0,14.76,15.41,21.41,27.39,1.98,3.58,2.02,2.99,5.61,1.92,3.23-.96,6.05-1.62,10.4-1.62,4.93-.42,12.62,3.32,13.92,2.09.51-.48.21-2.06.05-2.82-.11-.53-1.63-3.04-1.63-3.05ZM557.27,54.4h-9.56v-27.58h9.56c11.7,0,15.97,5.85,15.97,15.18s-4.27,12.4-15.97,12.4Z"
        />
      </svg>
    </div>
  )
}
